import { calcularDigitoCnj } from '../lib/cnj';
import { somarDias } from '../lib/datas';
import type { Dados, DataISO } from './types';

function cnj(sequencial: string, ano: string, segmento: string, tribunal: string, origem: string): string {
  const dv = calcularDigitoCnj(sequencial, ano, segmento, tribunal, origem);
  return `${sequencial}-${dv}.${ano}.${segmento}.${tribunal}.${origem}`;
}

